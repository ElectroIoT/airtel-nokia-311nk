# ------------------------------------------------------------------------------
# Phase 0: System Sanity & Environmental Validation
# ------------------------------------------------------------------------------
validate_environment() {
    log_info "Validating runtime environment and root privilege..."

    # Check effective user ID
    if [ "$(id -u 2>/dev/null || true)" != "0" ]; then
        log_error "This script must be executed as root (UID 0). Aborting."
        exit 1
    fi

    # Verify kernel architecture
    arch="$(uname -m 2>/dev/null || echo 'unknown')"
    kernel="$(uname -r 2>/dev/null || echo 'unknown')"
    log_info "Detected system: Architecture=${arch}, Kernel=${kernel}"

    # Verify writable mount points
    for dir in "${SYSTEMRW_DIR}" "${CONFIGS_DIR}"; do
        if [ ! -d "${dir}" ]; then
            log_warn "Directory ${dir} does not exist. Creating..."
            mkdir -p "${dir}" 2>/dev/null || true
        fi
        
        test_file="${dir}/.writetest.$$"
        if touch "${test_file}" 2>/dev/null; then
            rm -f "${test_file}" 2>/dev/null
            log_info "Storage target ${dir} verified writable."
        else
            log_warn "Storage target ${dir} is read-only or inaccessible. Attempting remount..."
            mount -o remount,rw "${dir}" 2>/dev/null || true
        fi
    done
}

# ------------------------------------------------------------------------------
# Phase 1: Hardware Watchdog & PCD Loop Neutralization
# ------------------------------------------------------------------------------
neutralize_watchdogs() {
    log_info "--- Phase 1: Disarming Hardware Watchdogs & PCD Deadman Switches ---"

    # 1. Create persistent dummy stub that returns exit code 0
    log_info "Deploying dummy success stub at ${DUMMY_STUB}..."
    cat << 'EOF' > "${DUMMY_STUB}"
#!/bin/sh
# Neutralized stub generated by nokia_odu_jio_unlock.sh
exit 0
EOF
    chmod 755 "${DUMMY_STUB}" 2>/dev/null || true

    # 2. Bind-mount dummy script over reboot-inducing scripts
    bind_targets="/bin/wd_pcdtest.sh /etc/watchdog.d/wdtest.sh /bin/postaction.sh"
    for target in ${bind_targets}; do
        if [ -e "${target}" ]; then
            if mount | grep -q " on ${target} "; then
                log_info "Target ${target} already intercepted via active bind-mount."
            else
                mount --bind "${DUMMY_STUB}" "${target}" 2>/dev/null
                if mount | grep -q " on ${target} "; then
                    log_success "Bind-mount active: ${DUMMY_STUB} -> ${target}"
                else
                    log_warn "Failed to bind-mount over ${target}."
                fi
            fi
        else
            log_info "Target script ${target} not present in this firmware build."
        fi
    done

    # 3. Create daemon stop flag tokens
    touch /tmp/stop_watchdog 2>/dev/null || true
    touch /tmp/pcd_stop 2>/dev/null || true
    rm -f /tmp/pcd_started 2>/dev/null || true

    # 4. Disarm short-boot tracker in persistent flash
    if [ -d "${CONFIGS_DIR}" ]; then
        log_info "Writing stable boot intervals into ${CONFIGS_DIR}/uptime to disarm PCD fallback..."
        printf '0:700\n0:700\n0:700\n0:700\n0:700\n' > "${CONFIGS_DIR}/uptime" 2>/dev/null || true
        log_success "PCD uptime counter pad applied (0:700)."
    fi
}

# ------------------------------------------------------------------------------
# Phase 2: QCMAP & EoGRE Disarming (Carrier Datapath Unblock)
# ------------------------------------------------------------------------------
patch_single_qcmap() {
    cfg_file="$1"
    [ -f "${cfg_file}" ] || return 0

    log_info "Processing QCMAP configuration: ${cfg_file}"
    tmp_file="/tmp/qcmap_patch_$$.tmp"
    cp -f "${cfg_file}" "${tmp_file}" 2>/dev/null || return 1

    # Apply deterministic sed substitutions
    # A. Backhaul priorities: Elevate wwan to FirstPreferredBackhaul
    sed -i "s|<FirstPreferredBackhaul>.*</FirstPreferredBackhaul>|<FirstPreferredBackhaul>wwan</FirstPreferredBackhaul>|g" "${tmp_file}"
    sed -i "s|<FifthPreferredBackhaul>.*</FifthPreferredBackhaul>|<FifthPreferredBackhaul>bt-pan</FifthPreferredBackhaul>|g" "${tmp_file}"

    # B. EoGRE Profile 1 Disarming & Bypass
    sed -i "s|<EoGREProfile1>1</EoGREProfile1>|<EoGREProfile1>0</EoGREProfile1>|g" "${tmp_file}"
    sed -i "s|<EoGREProfile1TunnelCount>1</EoGREProfile1TunnelCount>|<EoGREProfile1TunnelCount>0</EoGREProfile1TunnelCount>|g" "${tmp_file}"
    sed -i "s|<EoGREConfiguredForPDN>1</EoGREConfiguredForPDN>|<EoGREConfiguredForPDN>0</EoGREConfiguredForPDN>|g" "${tmp_file}"
    sed -i "s|<EoGRETunneledTraffic>3</EoGRETunneledTraffic>|<EoGRETunneledTraffic>0</EoGRETunneledTraffic>|g" "${tmp_file}"
    sed -i "s|<EoGRETunneledTraffic>1</EoGRETunneledTraffic>|<EoGRETunneledTraffic>0</EoGRETunneledTraffic>|g" "${tmp_file}"
    sed -i "s|<EoGRENonTunneledTraffic>0</EoGRENonTunneledTraffic>|<EoGRENonTunneledTraffic>1</EoGRENonTunneledTraffic>|g" "${tmp_file}"

    # C. APN Target Injection & AutoConnect
    sed -i "s|<APN_Name>.*</APN_Name>|<APN_Name>${TARGET_APN}</APN_Name>|g" "${tmp_file}"
    sed -i "s|<APN_Name />|<APN_Name>${TARGET_APN}</APN_Name>|g" "${tmp_file}"
    sed -i "s|<AutoConnect>0</AutoConnect>|<AutoConnect>1</AutoConnect>|g" "${tmp_file}"

    # Atomic write back to target
    cat "${tmp_file}" > "${cfg_file}" 2>/dev/null
    rm -f "${tmp_file}" 2>/dev/null
    log_success "Successfully patched and verified: ${cfg_file}"
}

disarm_qcmap_eogre() {
    log_info "--- Phase 2: Disarming Qualcomm QCMAP EoGRE & Injecting Jio APN ---"

    # Known QCMAP XML configuration files across active and persistent overlays
    qcmap_candidates="
    ${SYSTEMRW_DIR}/data/mobileap_cfg_b2c_494_1.xml
    ${SYSTEMRW_DIR}/data/mobileap_cfg.xml
    ${SYSTEMRW_DIR}/data/mobileap_cfg_460_1.xml
    /etc/data/mobileap_cfg.xml
    "

    found=0
    for file in ${qcmap_candidates}; do
        if [ -f "${file}" ]; then
            patch_single_qcmap "${file}"
            found=$((found + 1))
        fi
    done

    if [ "${found}" -eq 0 ]; then
        log_warn "No standard QCMAP XML files found. Checking alternate paths..."
    else
        log_info "Total QCMAP configurations updated: ${found}"
    fi

    # Restart QCMAP Connection Manager daemon if present
    if command -v systemctl >/dev/null 2>&1; then
        log_info "Restarting QCMAP_ConnectionManagerd service..."
        systemctl restart QCMAP_ConnectionManagerd 2>/dev/null || true
    elif [ -x /etc/init.d/qcmap_cm ]; then
        log_info "Restarting /etc/init.d/qcmap_cm..."
        /etc/init.d/qcmap_cm restart 2>/dev/null || true
    fi
}

# ------------------------------------------------------------------------------
# Phase 3: Datapath Routing & Netfilter IP Masquerading
# ------------------------------------------------------------------------------
configure_networking_and_firewall() {
    log_info "--- Phase 3: Configuring Kernel Routing, Masquerading & TCP MSS ---"

    # 1. Wait briefly for QCMAP to bind network devices if just restarted
    sleep 3

    # Switch Qualcomm SDX65 modem to physical SIM Slot 1 (Jio USIM tray)
    log_info "Ensuring Qualcomm SDX65 is switched to physical SIM Slot 1 (Jio USIM tray)..."
    exec 3<>/dev/smd11 2>/dev/null && {
        echo -e "AT+QUIMSLOT=1\r" >&3
        sleep 1
        echo -e "AT+CFUN=1\r" >&3
        sleep 0.5
        exec 3>&-
    }

    # 2. Enable Kernel Packet Forwarding for IPv4 & IPv6
    log_info "Enabling kernel IPv4 and IPv6 forwarding..."
    echo 1 > /proc/sys/net/ipv4/ip_forward 2>/dev/null || true
    echo 1 > /proc/sys/net/ipv6/conf/all/forwarding 2>/dev/null || true
    echo 1 > /proc/sys/net/ipv6/conf/default/forwarding 2>/dev/null || true
    echo 0 > /proc/sys/net/bridge/bridge-nf-call-iptables 2>/dev/null || true
    echo 0 > /proc/sys/net/bridge/bridge-nf-call-ip6tables 2>/dev/null || true
    echo 0 > /proc/sys/net/bridge/bridge-nf-call-arptables 2>/dev/null || true

    for f in /proc/sys/net/ipv4/conf/*/forwarding; do
        [ -f "${f}" ] && echo 1 > "${f}" 2>/dev/null || true
    done
    for f in /proc/sys/net/ipv6/conf/*/forwarding; do
        [ -f "${f}" ] && echo 1 > "${f}" 2>/dev/null || true
    done

    # Explicitly ensure bridge0 forwarding is enabled
    echo 1 > /proc/sys/net/ipv4/conf/bridge0/forwarding 2>/dev/null || true

    # 3. Kernel Buffer & Queue Tuning for Zero Packet Loss
    log_info "Optimizing kernel socket buffers, txqueuelen, and backlog queues..."
    for dev in eth0 eth0.1999 bridge0 rmnet_data0 rmnet_data1; do
        ip link set dev "$dev" txqueuelen 5000 2>/dev/null || true
    done
    sysctl -w net.core.netdev_max_backlog=16384 2>/dev/null || true
    sysctl -w net.core.somaxconn=4096 2>/dev/null || true
    sysctl -w net.core.rmem_max=16777216 2>/dev/null || true
    sysctl -w net.core.wmem_max=16777216 2>/dev/null || true
    sysctl -w net.core.rmem_default=1048576 2>/dev/null || true
    sysctl -w net.core.wmem_default=1048576 2>/dev/null || true
    sysctl -w net.ipv4.tcp_rmem="4096 87380 16777216" 2>/dev/null || true
    sysctl -w net.ipv4.tcp_wmem="4096 65536 16777216" 2>/dev/null || true
    sysctl -w net.ipv4.tcp_window_scaling=1 2>/dev/null || true
    sysctl -w net.ipv4.tcp_timestamps=1 2>/dev/null || true
    sysctl -w net.ipv4.tcp_sack=1 2>/dev/null || true
    sysctl -w net.netfilter.nf_conntrack_max=65536 2>/dev/null || true
    sysctl -w net.netfilter.nf_conntrack_tcp_timeout_established=7200 2>/dev/null || true
    sysctl -w net.ipv4.conf.all.rp_filter=0 2>/dev/null || true
    sysctl -w net.ipv4.conf.bridge0.rp_filter=0 2>/dev/null || true

    # 4. LAN Bridge Adjustments (Ensure bridge0 accepts standard Ethernet frames)
    if command -v brctl >/dev/null 2>&1; then
        ip addr del 169.254.51.1/24 dev eth0 2>/dev/null || true
        brctl delif br_gre eth0 2>/dev/null || true
        brctl addif bridge0 eth0 2>/dev/null || true
        echo 1 > /proc/sys/net/ipv4/conf/bridge0/forwarding 2>/dev/null || true
    fi

    # Explicitly permit DHCP (UDP 67/68) and bridge0/eth0 traffic
    iptables -C INPUT -p udp --dport 67:68 -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -p udp --dport 67:68 -j ACCEPT 2>/dev/null || true
    iptables -C INPUT -i bridge0 -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -i bridge0 -j ACCEPT 2>/dev/null || true
    iptables -C INPUT -i eth0 -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -i eth0 -j ACCEPT 2>/dev/null || true
    iptables -C FORWARD -i bridge0 -j ACCEPT 2>/dev/null || iptables -I FORWARD 1 -i bridge0 -j ACCEPT 2>/dev/null || true
    iptables -C FORWARD -o bridge0 -j ACCEPT 2>/dev/null || iptables -I FORWARD 1 -o bridge0 -j ACCEPT 2>/dev/null || true

    # 5. Inject Netfilter NAT Masquerading & Forwarding for all active/dormant cellular interfaces
    log_info "Injecting NAT masquerade & bidirectional fast-path for rmnet_data0 and rmnet_data1..."
    for wan in rmnet_data0 rmnet_data1; do
        iptables -t nat -C POSTROUTING -o "${wan}" -j MASQUERADE 2>/dev/null || \
            iptables -t nat -A POSTROUTING -o "${wan}" -j MASQUERADE 2>/dev/null || true

        iptables -C FORWARD -i bridge0 -o "${wan}" -j ACCEPT 2>/dev/null || \
            iptables -I FORWARD 1 -i bridge0 -o "${wan}" -j ACCEPT 2>/dev/null || true

        iptables -C FORWARD -i "${wan}" -o bridge0 -m state --state RELATED,ESTABLISHED -j ACCEPT 2>/dev/null || \
            iptables -I FORWARD 1 -i "${wan}" -o bridge0 -m state --state RELATED,ESTABLISHED -j ACCEPT 2>/dev/null || true
    done

    # 6. Apply Strict TCP MSS Clamping to eliminate 5G SA GTP-U / IPv6 Fragmentation Stalls
    log_info "Applying TCP MSS Clamping to prevent TLS handshake drop on 5G SA..."
    
    # Path MTU auto-clamp
    iptables -t mangle -C FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu 2>/dev/null || \
        iptables -t mangle -A FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu 2>/dev/null || true

    # Explicit IPv4 MSS Clamping (1360 bytes for optimal GTP-U encapsulation overhead)
    iptables -t mangle -C FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1360 2>/dev/null || \
        iptables -t mangle -A FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1360 2>/dev/null || true

    # Explicit IPv6 MSS Clamping (1340 bytes accounting for 40-byte IPv6 base header)
    if command -v ip6tables >/dev/null 2>&1; then
        ip6tables -t mangle -C FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1340 2>/dev/null || \
        ip6tables -t mangle -A FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1340 2>/dev/null || true
    fi

    # Final enforcement of bridge forwarding flag
    echo 1 > /proc/sys/net/ipv4/conf/bridge0/forwarding 2>/dev/null || true

    log_success "Kernel routing, buffer scaling, NAT masquerade, and TCP MSS clamping successfully active."
}

# ------------------------------------------------------------------------------
# Phase 4: Telemetry & Carrier Lockout Suppression
# ------------------------------------------------------------------------------
suppress_telemetry_and_lockouts() {
    log_info "--- Phase 4: Suppressing Telemetry, TR-069 ACS & Corteca USP ---"

    # 1. Terminate running USP and TR-369 agent daemons
    log_info "Terminating USP agent (nuspd)..."
    killall -9 nuspd 2>/dev/null || true

    # 2. Disable CWMP and USP in Nokia internal config engine via cfgcli if present
    if command -v cfgcli >/dev/null 2>&1; then
        log_info "Disabling CWMP & TR-369 USP via Nokia cfgcli..."
        cfgcli -s InternetGatewayDevice.ManagementServer.EnableCWMP false 2>/dev/null || true
        cfgcli -s InternetGatewayDevice.ManagementServer.X_ALU-COM_TR369Agent_Enable false 2>/dev/null || true
        cfgcli -s InternetGatewayDevice.ManagementServer.URL "http://127.0.0.1:8080" 2>/dev/null || true
        cfgcli --save-flash-now 2>/dev/null || true
    fi

    # 3. Clear USP primary controller pointer
    if [ -d "${CONFIGS_DIR}" ]; then
        echo "none" > "${CONFIGS_DIR}/uspprimController" 2>/dev/null || true
    fi

    # 4. Sinkhole Airtel ACS & Telemetry FQDNs in /etc/hosts
    log_info "Sinkholing carrier ACS and management domains to loopback in /etc/hosts..."
    for domain in ${SINKHOLE_DOMAINS}; do
        grep -q "[[:space:]]${domain}\$" /etc/hosts 2>/dev/null || \
            echo "127.0.0.1 ${domain}" >> /etc/hosts 2>/dev/null || true
        grep -q "[[:space:]]${domain}\$" /etc/hosts 2>/dev/null || \
            echo "::1 ${domain}" >> /etc/hosts 2>/dev/null || true
    done

    # 5. Drop Outbound Telemetry Ports at Netfilter Layer
    log_info "Rejecting outbound telemetry ports (8103, 5683, 8883)..."
    for port in 8103 5683 8883; do
        iptables -C OUTPUT -p tcp --dport "${port}" -j REJECT 2>/dev/null || \
            iptables -I OUTPUT 1 -p tcp --dport "${port}" -j REJECT 2>/dev/null || true
    done

    # 6. Clear Nokia Internal Traffic Blocks & Health Manager Alarms
    if command -v sysevent >/dev/null 2>&1; then
        log_info "Resetting proprietary sysevent blocking variables..."
        sysevent set CellularMgr_Block false 2>/dev/null || true
        sysevent set InitMgr_Block false 2>/dev/null || true
        sysevent set X_ALU_COM_AllowedForwarding_Block false 2>/dev/null || true
    fi

    # Reset LED Alarms (Illuminate Normal Green LED)
    if [ -x /bin/send_led_event.sh ]; then
        log_info "Updating system LED status to Operational Green..."
        /bin/send_led_event.sh -e 302 2>/dev/null || true
        /bin/send_led_event.sh -e 1102 2>/dev/null || true
        /bin/send_led_event.sh -e 1601 -a '{"Event":"2"}' 2>/dev/null || true
        /bin/send_led_event.sh -e 5817 -a '{"ActiveWAN":"Cellular"}' 2>/dev/null || true
    fi

    log_success "Telemetry and carrier lockout components completely neutralized."
}

