# ------------------------------------------------------------------------------
# Logging & Console Helpers
# ------------------------------------------------------------------------------
log() {
    level="$1"
    msg="$2"
    timestamp="$(date '+%Y-%m-%d %H:%M:%S' 2>/dev/null || echo '0000-00-00 00:00:00')"
    formatted="[${timestamp}] [${level}] ${msg}"
    
    # Output to stdout
    echo "${formatted}"
    
    # Append to persistent logfile
    echo "${formatted}" >> "${LOG_FILE}" 2>/dev/null || true
    
    # Dispatch to syslog via logger if available
    if command -v logger >/dev/null 2>&1; then
        case "${level}" in
            INFO)    logger -t "${LOG_TAG}" -p user.info    "${msg}" 2>/dev/null || true ;;
            WARN)    logger -t "${LOG_TAG}" -p user.warning "${msg}" 2>/dev/null || true ;;
            ERROR)   logger -t "${LOG_TAG}" -p user.err     "${msg}" 2>/dev/null || true ;;
            SUCCESS) logger -t "${LOG_TAG}" -p user.notice  "[SUCCESS] ${msg}" 2>/dev/null || true ;;
            *)       logger -t "${LOG_TAG}" -p user.info    "${msg}" 2>/dev/null || true ;;
        esac
    fi
}

log_info()    { log "INFO" "$1"; }
log_warn()    { log "WARN" "$1"; }
log_error()   { log "ERROR" "$1"; }
log_success() { log "SUCCESS" "$1"; }

# ------------------------------------------------------------------------------
# Trap & Error Recovery
# ------------------------------------------------------------------------------
cleanup() {
